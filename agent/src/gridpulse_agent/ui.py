"""Streamlit demo UI:  uv run streamlit run agent/src/gridpulse_agent/ui.py"""

import os

import httpx
import pandas as pd
import streamlit as st

API = os.environ.get("GRIDPULSE_AGENT_URL", "http://localhost:8091")
TOKEN = os.environ.get("GRIDPULSE_AGENT_API_TOKEN")

st.set_page_config(page_title="GridPulse assistant", page_icon="⚡", layout="wide")
st.title("⚡ GridPulse assistant")
st.caption(
    "Answers come only from governed metrics (MetricFlow over EIA-930 data). "
    "Every number is checked against the query result."
)

examples = [
    "Which balancing authority had the highest peak demand in July 2026?",
    "How accurate was ERCOT's day-ahead forecast in September 2026?",
    "What does data completeness measure?",
]
question = st.text_input(
    "Ask about U.S. grid demand, forecasts or data quality", placeholder=examples[0]
)
cols = st.columns(len(examples))
for col, example in zip(cols, examples, strict=True):
    if col.button(example, use_container_width=True):
        question = example

if question:
    headers = {"Authorization": f"Bearer {TOKEN}"} if TOKEN else {}
    with st.spinner("Planning a metric request and querying the semantic layer..."):
        resp = httpx.post(f"{API}/ask", json={"question": question}, headers=headers, timeout=180)
    if resp.status_code == 503:  # model or metrics API unavailable: the API explains why
        st.warning(resp.json().get("message", resp.text))
        st.stop()
    if resp.status_code != 200:
        st.error(f"{resp.status_code}: {resp.text}")
        st.stop()
    out = resp.json()
    badge = {"answered": "✅ numbers verified", "fallback_table": "⚠️ fallback to raw table"}.get(
        out["status"], out["status"]
    )
    st.markdown(f"**{badge}**")
    st.write(out["answer"])
    if out["rows"]:
        frame = pd.DataFrame(out["rows"], columns=out["columns"])
        time_cols = [c for c in frame.columns if c.startswith("metric_time")]
        if time_cols and not out["metric_request"]["order_by"]:  # time series read in time order
            frame = frame.sort_values(time_cols[0])
        st.dataframe(frame, use_container_width=True, hide_index=True)
        numeric = frame.select_dtypes("number").columns.tolist()
        if time_cols and numeric:
            st.line_chart(frame.set_index(time_cols[0])[numeric])
        elif len(frame) > 1 and numeric:
            st.bar_chart(frame.set_index(frame.columns[0])[numeric[0]])
    with st.expander("Metric request"):
        st.json(out["metric_request"] or {})
    with st.expander("SQL generated by MetricFlow"):
        st.code(out["sql"] or "", language="sql")
