"""Streamlit demo UI:  uv run streamlit run agent/src/gridpulse_agent/ui.py

A chat: each message goes to /ask/stream with the conversation's thread_id, so follow-ups
("and last year?") and replies to a clarifying question continue the same conversation.
"""

import json
import os

import httpx
import pandas as pd
import streamlit as st

API = os.environ.get("GRIDPULSE_AGENT_URL", "http://localhost:8091")
TOKEN = os.environ.get("GRIDPULSE_AGENT_API_TOKEN")

# What each graph step is doing, for the progress panel.
STEPS = {
    "route": "Classifying the question",
    "plan": "Planning a metric request",
    "validate": "Validating the request",
    "ambiguity": "Checking for ambiguity",
    "clarify": "Reading your answer",
    "execute": "Querying the semantic layer",
    "inspect": "Checking completeness and freshness",
    "answer": "Writing the answer",
    "ground_check": "Checking every number against the result",
    "remember": "Saving the conversation",
    "define": "Looking up the metric definition",
}

st.set_page_config(page_title="GridPulse assistant", page_icon="⚡", layout="wide")
st.title("⚡ GridPulse assistant")
st.caption(
    "Answers come only from governed metrics (MetricFlow over EIA-930 data). "
    "Every number is checked against the query result. Follow-ups continue the conversation."
)
if st.button("New conversation"):
    st.session_state.clear()
messages = st.session_state.setdefault("messages", [])


def show_result(out: dict) -> None:
    badge = {"answered": "✅ numbers verified", "fallback_table": "⚠️ fallback to raw table"}
    if out["status"] in badge:
        st.markdown(f"**{badge[out['status']]}**")
    st.markdown(out["answer"])
    if out["rows"]:
        frame = pd.DataFrame(out["rows"], columns=out["columns"])
        time_cols = [c for c in frame.columns if c.startswith("metric_time")]
        if time_cols and not out["metric_request"]["order_by"]:  # time series read in time order
            frame = frame.sort_values(time_cols[0])
        st.dataframe(frame, width="stretch", hide_index=True)
        numeric = frame.select_dtypes("number").columns.tolist()
        if time_cols and numeric:
            st.line_chart(frame.set_index(time_cols[0])[numeric])
        elif len(frame) > 1 and numeric:
            st.bar_chart(frame.set_index(frame.columns[0])[numeric[0]])
    if out.get("metric_request"):
        with st.expander("Metric request"):
            st.json(out["metric_request"])
    if out.get("sql"):
        with st.expander("SQL generated by MetricFlow"):
            st.code(out["sql"], language="sql")


def stream(question: str):
    """Events from /ask/stream (Server-Sent Events, one JSON object per `data:` line)."""
    headers = {"Authorization": f"Bearer {TOKEN}"} if TOKEN else {}
    body = {"question": question, "thread_id": st.session_state.get("thread_id")}
    with httpx.stream("POST", f"{API}/ask/stream", json=body, headers=headers, timeout=180) as resp:
        if resp.status_code != 200:
            resp.read()
            yield {"type": "error", "message": f"{resp.status_code}: {resp.text}"}
            return
        for line in resp.iter_lines():
            if line.startswith("data: "):
                yield json.loads(line[6:])


for message in messages:
    with st.chat_message(message["role"]):
        if message["role"] == "user":
            st.markdown(message["text"])
        else:
            show_result(message["out"])

# A fixed placeholder: Streamlit treats a chat input with different arguments as a new widget,
# so changing it (e.g. to "Your answer" while a question is pending) drops what was typed.
if question := st.chat_input("Ask about U.S. grid data, or answer my question"):
    messages.append({"role": "user", "text": question})
    with st.chat_message("user"):
        st.markdown(question)
    with st.chat_message("assistant"):
        out = None
        with st.status("Working...", expanded=False) as status:
            for event in stream(question):
                if event["type"] == "step":
                    status.update(label=STEPS.get(event["node"], event["node"]))
                elif event["type"] == "result":
                    out = event
                    status.update(label="Done", state="complete")
                else:  # model or metrics API unavailable: the API explains why
                    status.update(label="Unavailable", state="error")
                    st.warning(event.get("message", "Something went wrong."))
        if out:
            st.session_state["thread_id"] = out["thread_id"]
            messages.append({"role": "assistant", "out": out})
            show_result(out)
